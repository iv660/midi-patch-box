DisplayBitmapSplashScreenView::DisplayBitmapSplashScreenView(int sda_pin, int scl_pin, uint8_t i2c_address)
    : display(SCREEN_WIDTH, SCREEN_HEIGHT, &Wire, OLED_RESET)
    , isInitialized(false)
    , sdaPin(sda_pin)
    , sclPin(scl_pin)
    , i2cAddress(i2c_address)
{
    initializeDisplay();
}

DisplayBitmapSplashScreenView::~DisplayBitmapSplashScreenView()
{
    if (isInitialized) {
        display.clearDisplay();
        display.display();
    }
}

void DisplayBitmapSplashScreenView::showMessage()
{
    if (isInitialized) {
        displayBitmapSplash();
    }
}

void DisplayBitmapSplashScreenView::hide()
{
    if (isInitialized) {
        clearDisplay();
    }
}

void DisplayBitmapSplashScreenView::initializeDisplay()
{
    Wire.setSDA(sdaPin);
    Wire.setSCL(sclPin);
    Wire.begin();
    
    if (display.begin(SSD1306_SWITCHCAPVCC, i2cAddress)) {
        isInitialized = true;
        display.clearDisplay();
        display.display();
    }
}

void DisplayBitmapSplashScreenView::clearDisplay()
{
    display.clearDisplay();
    display.display();
}

void DisplayBitmapSplashScreenView::displayBitmapSplash()
{
    display.clearDisplay();
    
    // Display the bitmap image (128x64 pixels)
    display.drawBitmap(0, 0, epd_bitmap_splash_logo, SCREEN_WIDTH, SCREEN_HEIGHT, SSD1306_WHITE);
    
    display.display();
}